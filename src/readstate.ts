import { writeFile } from "node:fs/promises";
import { Db } from "mongodb";
import type { RcSubscription } from "./types.js";
import { toEpochMs } from "./util.js";

/**
 * Per-user read state, replayed onto Mattermost AFTER the import.
 *
 * Why SQL and not the import file: the bulk import cannot carry read state for
 * direct/group messages at all, and for channels it needs message counts that
 * only Mattermost knows exactly (its own totals, collapsed-thread root counts).
 *
 * RocketChat semantics reproduced, per (user, room) subscription:
 *  - shown as read (`alert` false and `unread` 0) → everything imported is read;
 *  - otherwise → read up to `ls`, the user's own messages always count as read
 *    (Mattermost never shows your own posts as unread; RocketChat's `ls` lags
 *    behind them), and the unread mention count is kept;
 *  - a channel membership that only exists because the user posted there (no
 *    RocketChat subscription) → read.
 *
 * The patch only ever moves read state forward: a membership the user has
 * already read further in Mattermost is left untouched, and posts created after
 * the cutoff (new Mattermost activity) always stay unread.
 */
export interface ReadStateInput {
  teamName: string;
  channelNameByRoom: Map<string, string>; // RC room id → MM channel name
  directMembersByRoom: Map<string, string[]>; // RC room id → MM usernames
  skipRooms: Set<string>; // e.g. discussions (merged into threads)
  usernameMap: Map<string, string>; // RC username → MM username
  // MM username → lowercased email. Users are matched by EMAIL in the SQL: an
  // SSO login may rename them (e.g. OpenID "UsePreferredUsername"), the email
  // stays.
  emailByUser: Map<string, string>;
  memberships: Map<string, Map<string, string>>; // MM user → channel → roles
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export async function writeReadStateSql(
  db: Db,
  input: ReadStateInput,
  outFile: string,
): Promise<{ rows: number; read: number; partial: number }> {
  const rows: string[] = [];
  let read = 0;
  let partial = 0;
  const subscribed = new Set<string>(); // "user\tchannel" pairs with a subscription

  const cursor = db
    .collection<RcSubscription>("rocketchat_subscription")
    .find({ t: { $in: ["c", "p", "d"] } })
    .addCursorFlag("noCursorTimeout", true);

  for await (const sub of cursor) {
    if (input.skipRooms.has(sub.rid)) continue;
    const user = input.usernameMap.get(sub.u?.username ?? "");
    const email = user && input.emailByUser.get(user);
    if (!user || !email) continue;

    let kind: "C" | "D" | "G";
    let ref: string;
    const channel = input.channelNameByRoom.get(sub.rid);
    if (channel) {
      kind = "C";
      ref = channel;
      subscribed.add(`${user}\t${channel}`);
    } else {
      const members = input.directMembersByRoom.get(sub.rid);
      if (!members?.includes(user)) continue;
      const emails = members.map((m) => input.emailByUser.get(m));
      if (emails.some((e) => !e)) continue;
      if (members.length === 2) {
        kind = "D";
        ref = input.emailByUser.get(members.find((m) => m !== user)!)!;
      } else {
        kind = "G";
        ref = (emails as string[]).sort().join(","); // code-point order = COLLATE "C"
      }
    }

    const isRead = !sub.alert && !(sub.unread && sub.unread > 0);
    const ls = sub.ls ? toEpochMs(sub.ls) : 0;
    const mentions = isRead ? 0 : Math.max(0, sub.userMentions ?? 0);
    if (isRead) read++;
    else partial++;
    rows.push(
      `(${q(email)},${q(kind)},${q(ref)},${ls},${isRead},${mentions})`,
    );
  }

  // Memberships without any RocketChat subscription (author-only) → read.
  for (const [user, channels] of input.memberships) {
    const email = input.emailByUser.get(user);
    if (!email) continue;
    for (const channel of channels.keys()) {
      if (subscribed.has(`${user}\t${channel}`)) continue;
      rows.push(`(${q(email)},'C',${q(channel)},0,true,0)`);
      read++;
    }
  }

  const sql: string[] = [
    "-- Per-user read-state patch generated by rocket2matter.",
    "-- Run AFTER the import against the Mattermost database, setting :cutoff to",
    "-- the import start time in ms (posts created after it are new activity):",
    "--   psql -v cutoff=<epoch_ms> -v ON_ERROR_STOP=1 -f readstate.sql <db>",
    "\\if :{?cutoff}",
    "\\else",
    "SELECT (extract(epoch FROM now()) * 1000)::bigint AS cutoff \\gset",
    "\\endif",
    "BEGIN;",
    "CREATE TEMP TABLE r2m_rs (email text, kind text, ref text, ls bigint, is_read boolean, mentions int) ON COMMIT DROP;",
  ];
  for (let i = 0; i < rows.length; i += 500) {
    sql.push(`INSERT INTO r2m_rs VALUES\n${rows.slice(i, i + 500).join(",\n")};`);
  }
  sql.push(
    // Resolve (user, channel) ids for the three kinds of channels.
    "CREATE TEMP TABLE r2m_res ON COMMIT DROP AS",
    "  SELECT u.id AS userid, c.id AS channelid, rs.ls, rs.is_read, rs.mentions",
    "    FROM r2m_rs rs JOIN users u ON lower(u.email) = rs.email",
    `    JOIN channels c ON c.name = rs.ref AND c.teamid = (SELECT id FROM teams WHERE name = ${q(input.teamName)})`,
    "   WHERE rs.kind = 'C'",
    "  UNION ALL",
    "  SELECT u.id, c.id, rs.ls, rs.is_read, rs.mentions",
    "    FROM r2m_rs rs JOIN users u ON lower(u.email) = rs.email",
    "    JOIN users o ON lower(o.email) = rs.ref",
    "    JOIN channels c ON c.type = 'D' AND c.name = LEAST(u.id, o.id) || '__' || GREATEST(u.id, o.id)",
    "   WHERE rs.kind = 'D'",
    "  UNION ALL",
    "  SELECT u.id, g.id, rs.ls, rs.is_read, rs.mentions",
    "    FROM r2m_rs rs JOIN users u ON lower(u.email) = rs.email",
    "    JOIN (SELECT c.id, string_agg(lower(u2.email), ',' ORDER BY lower(u2.email) COLLATE \"C\") AS members",
    "            FROM channels c JOIN channelmembers x ON x.channelid = c.id JOIN users u2 ON u2.id = x.userid",
    "           WHERE c.type = 'G' GROUP BY c.id) g ON g.members = rs.ref",
    "   WHERE rs.kind = 'G';",
    // Read up to X: X = cutoff when RocketChat shows it read, else ls.
    "UPDATE channelmembers cm SET",
    "    lastviewedat = x.seen,",
    "    msgcount     = GREATEST(cm.msgcount,     c.totalmsgcount     - x.unread_all),",
    "    msgcountroot = GREATEST(cm.msgcountroot, c.totalmsgcountroot - x.unread_root),",
    "    mentioncount = x.mentions, mentioncountroot = x.mentions, urgentmentioncount = 0,",
    // Clients sync channel members incrementally (since lastupdateat): without
    // bumping it, an already-connected client keeps the stale unread state.
    "    lastupdateat = (extract(epoch FROM now()) * 1000)::bigint",
    "  FROM (",
    "    SELECT r.userid, r.channelid, r.mentions,",
    "           CASE WHEN r.is_read THEN :cutoff ELSE LEAST(r.ls, :cutoff) END AS seen,",
    "           (SELECT count(*) FROM posts p WHERE p.channelid = r.channelid AND p.deleteat = 0",
    "               AND p.userid <> r.userid",
    "               AND p.createat > CASE WHEN r.is_read THEN :cutoff ELSE r.ls END) AS unread_all,",
    "           (SELECT count(*) FROM posts p WHERE p.channelid = r.channelid AND p.deleteat = 0",
    "               AND p.rootid = '' AND p.userid <> r.userid",
    "               AND p.createat > CASE WHEN r.is_read THEN :cutoff ELSE r.ls END) AS unread_root",
    "      FROM r2m_res r",
    "  ) x JOIN channels c ON c.id = x.channelid",
    " WHERE cm.userid = x.userid AND cm.channelid = x.channelid",
    // Never move backwards: skip memberships already read further in
    // Mattermost (the import itself may have set lastviewedat = ls, hence <=).
    "   AND cm.lastviewedat <= x.seen;",
    "COMMIT;",
  );

  await writeFile(outFile, sql.join("\n") + "\n");
  return { rows: rows.length, read, partial };
}
